Run-Test '17' "Large library ($LargeCount files)" 'Executed' {
    $L = New-Library 'large'
    $PerFolder = 20
    $FolderCount = [math]::Ceiling($LargeCount / $PerFolder)
    $Made = 0
    for ($f = 1; $f -le $FolderCount -and $Made -lt $LargeCount; $f++) {
        $Dir = Join-Path $L ("Artist {0:D3}/Album {0:D3}" -f $f)
        [void][System.IO.Directory]::CreateDirectory($Dir)
        for ($t = 1; $t -le $PerFolder -and $Made -lt $LargeCount; $t++) {
            [System.IO.File]::WriteAllBytes((Join-Path $Dir ("{0:D2} - Track {0}.flac" -f $t)), [byte[]]@(0))
            $Made++
        }
    }
    $Clock = [System.Diagnostics.Stopwatch]::StartNew()
    $r1 = Invoke-Generator $L
    $First = $Clock.Elapsed.TotalSeconds
    $Clock.Restart()
    $r2 = Invoke-Generator $L
    $Second = $Clock.Elapsed.TotalSeconds
    Assert ($r1.ExitCode -eq 0 -and $r2.ExitCode -eq 0) 'both runs exit 0'
    Assert ((Get-Count $r1 'Tracks indexed') -eq $LargeCount) "indexed $LargeCount tracks"
    Assert ((Get-Count $r1 'Playlists created') -eq $FolderCount) "created $FolderCount playlists"
    Assert ((Get-Count $r2 'Playlists unchanged') -eq $FolderCount) 'second run changes nothing'
    "{0} files / {1} folders: first run {2:N1}s, unchanged rerun {3:N1}s" -f $LargeCount, ($FolderCount * 2 + 1), $First, $Second
}


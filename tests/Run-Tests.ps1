    $Names = @("Caf$([char]0xE9) $([char]0x2013) $([char]0xD1)and$([char]0xFA).flac", "$([char]0x65E5)$([char]0x672C)$([char]0x8A9E).mp3", ("Emoji " + [char]::ConvertFromUtf32(0x1F3B5) + '.opus'))

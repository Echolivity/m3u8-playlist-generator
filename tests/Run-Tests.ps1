Run-Test '01' 'Empty library' 'Executed' {
    $L = New-Library 'empty'
    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    Assert (@(Get-Playlists $L).Count -eq 0) 'no playlists created'
    Assert ((Get-Count $r 'Folders scanned') -eq 1) 'one folder scanned'
}

Run-Test '02' 'Single album: exact output format' 'Executed' {
    $L = New-Library 'single'
    New-Audio $L @('Album/01 - Intro.mp3', 'Album/02 - Song.flac', 'Album/cover.jpg')
    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    Assert-Equal @('Album' + [System.IO.Path]::DirectorySeparatorChar + 'Album.m3u8') (Get-Playlists $L) 'one playlist named after the folder'
    $Bytes = Get-Bytes (Join-Path $L 'Album/Album.m3u8')
    Assert (-not ($Bytes[0] -eq 0xEF -and $Bytes[1] -eq 0xBB -and $Bytes[2] -eq 0xBF)) 'no UTF-8 BOM'
    $Expected = "#EXTM3U`r`n$Tag`r`n#EXTINF:-1,01 - Intro`r`n01 - Intro.mp3`r`n#EXTINF:-1,02 - Song`r`n02 - Song.flac`r`n"
    Assert-Equal @($Expected) @($Utf8.GetString($Bytes)) 'exact playlist content (CRLF, tag, relative names)'
}

Run-Test '03' 'Nested album folders' 'Executed' {
    $L = New-Library 'nested'
    New-Audio $L @('Artist/Album A/a1.mp3', 'Artist/Album A/Disc 2/d1.mp3', 'Artist/Album B/b1.ogg', 'Artist/notes.txt', 'top.mp3')
    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    $s = [System.IO.Path]::DirectorySeparatorChar
    $Expected = @("Artist${s}Album A${s}Album A.m3u8", "Artist${s}Album A${s}Disc 2${s}Disc 2.m3u8", "Artist${s}Album B${s}Album B.m3u8", 'nested.m3u8') | Sort-Object
    Assert-Equal $Expected (Get-Playlists $L) 'playlist per audio folder, none for folders without audio'
    Assert-Equal @('a1.mp3') (Get-Entries (Join-Path $L 'Artist/Album A/Album A.m3u8')) 'only direct files listed'
    Assert-Equal @('top.mp3') (Get-Entries (Join-Path $L 'nested.m3u8')) 'root playlist lists root files only'
}

Run-Test '04' 'Unicode file and folder names' 'Executed' {
    $L = New-Library 'unicode'

Run-Test '08' 'Manually created playlists are never modified' 'Executed' {
    $L = New-Library 'manual'
    $Cases = [ordered]@{
        'Abs'      = "#EXTM3U`r`nC:\Music\Abs\x.mp3`r`n"
        'Edited'   = "#EXTM3U`r`n$Tag`r`n#EXTINF:-1,x`r`nx.mp3`r`nhttp://radio.example/stream`r`n"
        'Duration' = "#EXTM3U`r`n#EXTINF:215,x`r`nx.mp3`r`n"
        'Retitled' = "#EXTM3U`r`n$Tag`r`n#EXTINF:-1,My favourite`r`nx.mp3`r`n"
        'Empty'    = ''
        'Plain'    = "x.mp3`r`n"
    }
    $Snap = @{}
    foreach ($K in $Cases.Keys) {
        New-Audio $L @("$K/x.mp3", "$K/y.mp3")
        [System.IO.File]::WriteAllText((Join-Path $L "$K/$K.m3u8"), $Cases[$K], $Utf8)
    }
    # Not valid UTF-8 (Windows-1252 bytes): ownership cannot be established.
    New-Audio $L @('Ansi/x.mp3')
    [System.IO.File]::WriteAllBytes((Join-Path $L 'Ansi/Ansi.m3u8'), [byte[]]@(0x23, 0x45, 0x58, 0x54, 0x4D, 0x33, 0x55, 0x0D, 0x0A, 0x43, 0x61, 0x66, 0xE9, 0x2E, 0x6D, 0x70, 0x33, 0x0D, 0x0A))
    # A user's own playlist in a folder that has no audio must never be removed.
    [void][System.IO.Directory]::CreateDirectory((Join-Path $L 'Lists'))
    [System.IO.File]::WriteAllText((Join-Path $L 'Lists/Lists.m3u8'), "#EXTM3U`r`n..\Abs\x.mp3`r`n", $Utf8)
    foreach ($P in Get-Playlists $L) { $Snap[$P] = Get-Bytes (Join-Path $L $P) }

    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    foreach ($P in $Snap.Keys) { Assert (Test-SameBytes $Snap[$P] (Get-Bytes (Join-Path $L $P))) "unchanged: $P" }
    Assert ((Get-Count $r 'Kept (not ours)') -eq 7) "7 playlists reported kept, got $(Get-Count $r 'Kept (not ours)')"
    Assert ((Get-Count $r 'Stale removed') -eq 0) 'nothing removed'
}

Run-Test '09' 'Empty-folder and renamed-folder reconciliation' 'Executed' {
    $L = New-Library 'reconcile'
    New-Audio $L @('Gone/1.mp3', 'Old Name/1.mp3', 'Old Name/2.mp3', 'Copy/9.mp3', 'LegacyGone/1.mp3')
    [void](Invoke-Generator $L)
    [System.IO.File]::WriteAllText((Join-Path $L 'LegacyGone/LegacyGone.m3u8'), "#EXTM3U`r`n#EXTINF:-1,1`r`n1.mp3`r`n", $Utf8)
    # A user's copy of another folder's generated playlist, under another name.
    [System.IO.File]::Copy((Join-Path $L 'Old Name/Old Name.m3u8'), (Join-Path $L 'Copy/Favourites.m3u8'))
    # Curated copies inside the same folder: a subset, and a reordered list.
    [System.IO.File]::WriteAllText((Join-Path $L 'Old Name/Best of.m3u8'), "#EXTM3U`r`n$Tag`r`n#EXTINF:-1,2`r`n2.mp3`r`n", $Utf8)
    [System.IO.File]::WriteAllText((Join-Path $L 'Old Name/Reversed.m3u8'), "#EXTM3U`r`n$Tag`r`n#EXTINF:-1,2`r`n2.mp3`r`n#EXTINF:-1,1`r`n1.mp3`r`n", $Utf8)

    Remove-Item -LiteralPath (Join-Path $L 'Gone/1.mp3'), (Join-Path $L 'LegacyGone/1.mp3')
    Rename-Item -LiteralPath (Join-Path $L 'Old Name') 'New Name'
    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    Assert (-not (Test-Path -LiteralPath (Join-Path $L 'Gone/Gone.m3u8'))) 'generated playlist of emptied folder removed'
    Assert (Test-Path -LiteralPath (Join-Path $L 'LegacyGone/LegacyGone.m3u8')) 'untagged (pre-1.0.0) playlist in emptied folder kept'
    Assert (Test-Path -LiteralPath (Join-Path $L 'New Name/New Name.m3u8')) 'renamed folder gets new playlist'
    Assert (-not (Test-Path -LiteralPath (Join-Path $L 'New Name/Old Name.m3u8'))) 'old-name playlist removed'
    Assert (Test-Path -LiteralPath (Join-Path $L 'Copy/Favourites.m3u8')) 'copied playlist with foreign entries kept'
    Assert (Test-Path -LiteralPath (Join-Path $L 'New Name/Best of.m3u8')) 'curated subset copy kept'
    Assert (Test-Path -LiteralPath (Join-Path $L 'New Name/Reversed.m3u8')) 'reordered copy kept'
    Assert ((Get-Count $r 'Stale removed') -eq 2) "2 stale removed, got $(Get-Count $r 'Stale removed')"
}


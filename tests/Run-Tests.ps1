Run-Test '12' 'System files excluded' $SystemMode {
    $L = New-Library 'systemfiles'
    New-Audio $L @('A/normal.mp3', 'A/sysfile.mp3')
    $Patch = $null
    if ($OnWindows) { Set-SystemAttr (Join-Path $L 'A/sysfile.mp3') }
    else {
        # Linux has no System attribute: make the generator see one on 'sys*' names.
        $Patch = @{ '$Attr = $Item.Attributes' = '$Attr = $Item.Attributes; if ($Item.Name -like ''sys*'') { $Attr = $Attr -bor [System.IO.FileAttributes]::System }' }
    }
    $r = Invoke-Generator $L $Patch
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    Assert-Equal @('normal.mp3') (Get-Entries (Join-Path $L 'A/A.m3u8')) 'system file excluded'
    if (-not $OnWindows) { 'System attribute injected by patching the attribute read; the bitwise check itself ran unmodified.' }
}

Run-Test '13' 'Hidden and system folders skipped' $SystemMode {
    $L = New-Library 'hiddendirs'
    $Patch = $null
    if ($OnWindows) {
        New-Audio $L @('Shown/a.mp3', 'Secret/a.mp3', 'SysDir/a.mp3')
        Set-Hidden (Join-Path $L 'Secret')
        Set-SystemAttr (Join-Path $L 'SysDir')
    }

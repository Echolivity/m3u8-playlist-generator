Run-Test '16d' 'Leftovers from a killed run are cleaned up safely' 'Executed' {
    $L = New-Library 'orphans'
    New-Audio $L @('A/1.mp3')
    [void](Invoke-Generator $L)
    $A = Join-Path $L 'A'
    $Old = [datetime]::UtcNow.AddHours(-1)
    $Generated = [System.IO.File]::ReadAllText((Join-Path $A 'A.m3u8'))
    $Files = @{
        '~M3U8-00000000000000a1.tmp' = @('partial', $Old, $false)
        '~M3U8-00000000000000a2.bak' = @($Generated, $Old, $false)
        '~M3U8-00000000000000a3.bak' = @("#EXTM3U`r`nC:\mine.mp3`r`n", $Old, $true)
        '~M3U8-00000000000000a4.tmp' = @('in use', [datetime]::UtcNow, $true)
        '~M3U8-notours.tmp'           = @('user file', $Old, $true)
    }
    foreach ($N in $Files.Keys) {
        $F = Join-Path $A $N
        [System.IO.File]::WriteAllText($F, $Files[$N][0], $Utf8)
        [System.IO.File]::SetLastWriteTimeUtc($F, $Files[$N][1])
    }
    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    foreach ($N in $Files.Keys) {
        $Exists = Test-Path -LiteralPath (Join-Path $A $N)
        Assert ($Exists -eq $Files[$N][2]) "$N should $(if ($Files[$N][2]) { 'remain' } else { 'be removed' })"
    }
    Assert ((Get-Count $r 'Work files cleaned') -eq 2) 'two leftovers removed'
}


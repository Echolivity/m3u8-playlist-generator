Run-Test '07' 'Existing generated playlist: update and no-op rerun' 'Executed' {
    $L = New-Library 'update'
    New-Audio $L @('A/1.mp3', 'A/2.mp3')
    [void](Invoke-Generator $L)
    New-Audio $L @('A/3.mp3')
    $r = Invoke-Generator $L
    Assert ($r.ExitCode -eq 0) "exit code 0, got $($r.ExitCode)"
    Assert ((Get-Count $r 'Playlists updated') -eq 1) 'one playlist updated'
    Assert-Equal @('1.mp3', '2.mp3', '3.mp3') (Get-Entries (Join-Path $L 'A/A.m3u8')) 'new track listed'
    $Before = Get-Item -LiteralPath (Join-Path $L 'A/A.m3u8')
    $Stamp = $Before.LastWriteTimeUtc
    Start-Sleep -Milliseconds 1100
    $r = Invoke-Generator $L
    Assert ((Get-Count $r 'Playlists unchanged') -eq 1) 'rerun reports unchanged'
    Assert ((Get-Item -LiteralPath (Join-Path $L 'A/A.m3u8')).LastWriteTimeUtc -eq $Stamp) 'unchanged playlist not rewritten'
    Assert (@(Get-WorkFiles $L).Count -eq 0) 'no work files left'
}


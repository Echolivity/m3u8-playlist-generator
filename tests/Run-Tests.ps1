<#
.SYNOPSIS
    Automated tests for Generate-M3U8.bat.

.DESCRIPTION
    Builds throw-away music libraries in a temporary folder, runs the generator
    against them and checks the results.

    On Windows the real BAT file is copied into each test library and run
    through cmd.exe, exactly as a user would run it; the BAT starts Windows
    PowerShell 5.1 itself. Run this script from Windows PowerShell 5.1
    (powershell.exe) or PowerShell 7 - the generator always uses powershell.exe.

    On Linux/macOS the BAT's own PowerShell start-up command is extracted and
    run with the current pwsh, so the embedded-script loader, exit codes and
    all generator code are exercised; cmd.exe and Windows-only behaviour are not.

    Every result is labelled:
      PASS      executed for real and passed
      PASS*     executed with an injected fault or simulated attribute (see Mode)
      FAIL      executed and failed
      SKIP      not possible on this platform / account; reason given

.PARAMETER Bat
    Path to Generate-M3U8.bat. Defaults to the one next to this folder.

.PARAMETER LargeCount
    Number of audio files in the large-library test (default 10000).

.PARAMETER Only
    Run only tests whose name contains this text.

.PARAMETER Report
    Write a Markdown report to this path.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File tests\Run-Tests.ps1 -Report tests\results-windows.md
#>
[CmdletBinding()]
param(
    [string]$Bat = (Join-Path (Split-Path -Parent $PSScriptRoot) 'Generate-M3U8.bat'),
    [int]$LargeCount = 10000,
    [string]$Only = '',
    [string]$Report = ''
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2

$OnWindows = [System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT
$Utf8 = [System.Text.UTF8Encoding]::new($false)
$Tag = '# Generated by M3U8 Playlist Generator (Echolivity)'
$BatText = [System.IO.File]::ReadAllText((Resolve-Path -LiteralPath $Bat).Path)
$WorkRoot = Join-Path ([System.IO.Path]::GetTempPath()) ('m3u8-tests-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
[void][System.IO.Directory]::CreateDirectory($WorkRoot)
$Results = [System.Collections.Generic.List[object]]::new()
$IsRoot = $false
if (-not $OnWindows) { $IsRoot = ((& id -u) -eq '0') }

# ----------------------------------------------------------------------------
# Harness
# ----------------------------------------------------------------------------

function Skip([string]$Reason) { throw ('SKIP: ' + $Reason) }

function Assert([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw "Assertion failed: $Message" }
}

function Assert-Equal($Expected, $Actual, [string]$Message) {
    if (($Expected -join "`n") -cne ($Actual -join "`n")) {
        throw "Assertion failed: $Message`n    expected: $($Expected -join ' | ')`n    actual  : $($Actual -join ' | ')"
    }
}

function New-Library([string]$Name) {
    $Path = Join-Path $WorkRoot $Name
    [void][System.IO.Directory]::CreateDirectory($Path)
    return $Path
}

function New-Audio([string]$Library, [string[]]$RelativePaths) {
    foreach ($Rel in $RelativePaths) {
        $Full = Join-Path $Library $Rel
        [void][System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($Full))
        [System.IO.File]::WriteAllBytes($Full, [byte[]]@(0x49, 0x44, 0x33))
    }
}

function Get-Bytes([string]$Path) { return ,([System.IO.File]::ReadAllBytes($Path)) }

function Test-SameBytes([byte[]]$A, [byte[]]$B) {
    if ($A.Length -ne $B.Length) { return $false }
    for ($i = 0; $i -lt $A.Length; $i++) { if ($A[$i] -ne $B[$i]) { return $false } }
    return $true
}

# File-name entries of a playlist, in order (lines that are not '#' lines).
function Get-Entries([string]$Path) {
    $Text = [System.IO.File]::ReadAllText($Path, [System.Text.UTF8Encoding]::new($false, $true))
    return @($Text -split "`r`n" | Where-Object { $_.Length -gt 0 -and -not $_.StartsWith('#') })
}

function Get-Playlists([string]$Library) {
    return @(Get-ChildItem -LiteralPath $Library -Recurse -Force -File -Filter '*.m3u8' | ForEach-Object { $_.FullName.Substring($Library.Length + 1) } | Sort-Object)
}

function Get-WorkFiles([string]$Library) {
    return @(Get-ChildItem -LiteralPath $Library -Recurse -Force -File | Where-Object { $_.Name -match '^~M3U8-' })
}

# Applies text patches to the BAT (fault injection / simulation). Each patch
# target must exist, so a test cannot silently stop injecting its fault.
function Get-PatchedBat([hashtable]$Patches) {
    $Text = $BatText
    if ($Patches) {
        foreach ($Key in $Patches.Keys) {
            if ($Text.IndexOf($Key, [System.StringComparison]::Ordinal) -lt 0) { throw "Patch target not found in BAT: $Key" }
            $Text = $Text.Replace($Key, $Patches[$Key])
        }
    }
    return $Text
}

# Runs the generator on a library. Returns exit code and console output.
function Invoke-Generator([string]$Library, [hashtable]$Patches = $null, [string]$RootOverride = $null) {
    $Text = Get-PatchedBat $Patches
    if ($OnWindows) {
        $BatPath = Join-Path $Library 'Generate-M3U8.bat'
        [System.IO.File]::WriteAllText($BatPath, $Text, $Utf8)
        $env:M3U8_NO_PAUSE = '1'
        try {
            $Output = & cmd.exe /d /c "`"$BatPath`"" 2>&1 | Out-String
            $Code = $LASTEXITCODE
        }
        finally {
            Remove-Item Env:\M3U8_NO_PAUSE -ErrorAction SilentlyContinue
            Remove-Item -LiteralPath $BatPath -Force -ErrorAction SilentlyContinue
        }
    }
    else {
        $BatPath = Join-Path $WorkRoot ('gen-' + [guid]::NewGuid().ToString('N').Substring(0, 8) + '.bat')
        [System.IO.File]::WriteAllText($BatPath, $Text, $Utf8)
        # The exact -Command string the BAT passes to powershell.exe.
        $Line = @($Text -split "`r`n" | Where-Object { $_.StartsWith('powershell.exe ') })[0]
        $Start = $Line.IndexOf('-Command "') + 10
        $Wrapper = $Line.Substring($Start, $Line.LastIndexOf('"') - $Start)
        $Root = $Library + [System.IO.Path]::DirectorySeparatorChar
        if ($RootOverride) { $Root = $RootOverride }
        $env:M3U8_ROOT = $Root
        $env:M3U8_BATCH = $BatPath
        try {
            $Pwsh = (Get-Process -Id $PID).Path
            $Output = & $Pwsh -NoLogo -NoProfile -Command $Wrapper 2>&1 | Out-String
            $Code = $LASTEXITCODE
        }
        finally {
            Remove-Item Env:\M3U8_ROOT, Env:\M3U8_BATCH -ErrorAction SilentlyContinue
            Remove-Item -LiteralPath $BatPath -Force -ErrorAction SilentlyContinue
        }
    }
    return [pscustomobject]@{ ExitCode = $Code; Output = $Output }
}

function Get-Count($Run, [string]$Label) {
    $m = [regex]::Match($Run.Output, [regex]::Escape($Label) + '\s*:\s*(\d+)')
    if (-not $m.Success) { throw "Summary line '$Label' not found in output:`n$($Run.Output)" }
    return [int]$m.Groups[1].Value
}

function Set-Hidden([string]$Path) {
    if (-not $OnWindows) { throw 'Set-Hidden is Windows-only' }
    $Item = Get-Item -LiteralPath $Path -Force
    $Item.Attributes = $Item.Attributes -bor [System.IO.FileAttributes]::Hidden
}

function Set-SystemAttr([string]$Path) {
    $Item = Get-Item -LiteralPath $Path -Force
    $Item.Attributes = $Item.Attributes -bor [System.IO.FileAttributes]::System
}

function Set-ReadOnlyFile([string]$Path, [bool]$On) {
    $Attr = [System.IO.File]::GetAttributes($Path)
    if ($On) { $Attr = $Attr -bor [System.IO.FileAttributes]::ReadOnly }
    else { $Attr = $Attr -band (-bnot [System.IO.FileAttributes]::ReadOnly) }
    [System.IO.File]::SetAttributes($Path, $Attr)
}

# Denies creating files in a folder (write) or listing it (read).
function Set-FolderAccess([string]$Path, [string]$Mode) {
    if ($OnWindows) {
        $Sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
        switch ($Mode) {
            'NoWrite' { & icacls $Path /deny "*${Sid}:(WD,AD)" | Out-Null }
            'NoRead'  { & icacls $Path /deny "*${Sid}:(RD)" | Out-Null }
            'Restore' { & icacls $Path /remove:d "*$Sid" | Out-Null }
        }
        if ($LASTEXITCODE -ne 0) { throw "icacls failed ($Mode) on $Path" }
    }
    else {
        switch ($Mode) {
            'NoWrite' { & chmod 555 $Path }
            'NoRead'  { & chmod 000 $Path }
            'Restore' { & chmod 755 $Path }
        }
    }
}

function Test-PermissionsEnforced {
    if ($OnWindows) { return $true }
    return -not $IsRoot
}

function Run-Test([string]$Id, [string]$Name, [string]$Mode, [scriptblock]$Body) {
    if ($Only -and ("$Id $Name") -notlike "*$Only*") { return }
    $Clock = [System.Diagnostics.Stopwatch]::StartNew()
    $Status = 'PASS'
    $Detail = ''
    try {
        $Extra = & $Body
        if ($Extra) { $Detail = ($Extra | Out-String).Trim() }
        if ($Mode -ne 'Executed') { $Status = 'PASS*' }
    }
    catch {
        if ($_.Exception.Message.StartsWith('SKIP: ')) { $Status = 'SKIP'; $Detail = $_.Exception.Message.Substring(6) }
        else { $Status = 'FAIL'; $Detail = ($_ | Out-String).Trim() }
    }
    $Clock.Stop()
    $Results.Add([pscustomobject]@{ Id = $Id; Name = $Name; Mode = $Mode; Status = $Status; Seconds = [math]::Round($Clock.Elapsed.TotalSeconds, 2); Detail = $Detail })
    $Colour = @{ 'PASS' = 'Green'; 'PASS*' = 'Green'; 'FAIL' = 'Red'; 'SKIP' = 'Yellow' }[$Status]
    Write-Host ("[{0,-5}] {1,-4} {2}  ({3})" -f $Status, $Id, $Name, $Mode) -ForegroundColor $Colour
    if ($Status -ne 'PASS' -and $Status -ne 'PASS*' -and $Detail) { Write-Host ('        ' + ($Detail -replace "`n", "`n        ")) }
}

